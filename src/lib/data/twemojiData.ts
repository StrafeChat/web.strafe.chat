// Create a flat map for quick emoji lookup by shortcode
export const emojiMap: Record<string, TwemojiEmoji> = {};
twemojiCategories.forEach((category) => {
  category.emojis.forEach((emoji) => {
    emojiMap[emoji.shortcode] = { ...emoji, category: category.name };
  });
});

// Helper function to get twemoji URL
export const getTwemojiUrl = (code: string): string => {
  return `${FS_URL}/twemoji/${code}.svg`;
};

// Helper function to get emoji by shortcode
export const getEmojiByShortcode = (
  shortcode: string,
): TwemojiEmoji | undefined => {
  return emojiMap[shortcode];
};

// Get Twemoji URL from shortcode
export const getTwemojiUrlFromShortcode = (
  shortcode: string,
): string | null => {
  const cleanShortcode = shortcode.replace(/^:|:$/g, "");
  const emoji = getEmojiByShortcode(cleanShortcode);
  return emoji ? getTwemojiUrl(emoji.code) : null;
};

// Validate shortcode format
export const isValidShortcode = (shortcode: string): boolean => {
  const cleanShortcode = shortcode.replace(/^:|:$/g, "");
  return emojiMap.hasOwnProperty(cleanShortcode);
};

// Get emoji data from shortcode
export const getEmojiDataFromShortcode = (
  shortcode: string,
): TwemojiEmoji | null => {
  const cleanShortcode = shortcode.replace(/^:|:$/g, "");
  return emojiMap[cleanShortcode] || null;
};

// Helper function to parse emoji shortcodes in text
export const parseEmojiShortcodes = (text: string): string => {
  return text.replace(/:(\w+):/g, (match, shortcode) => {
    const emoji = getEmojiByShortcode(shortcode);
    if (emoji) {
      return `<img src="${getTwemojiUrl(emoji.code)}" alt="${emoji.name}" class="inline-emoji" style="width: 1.2em; height: 1.2em; vertical-align: -0.1em;" />`;
    }
    return match;
  });
};
